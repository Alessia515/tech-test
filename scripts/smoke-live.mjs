import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { validateSql } from '../src/sql-validator.ts';
const base = process.env.API_BASE ?? 'http://127.0.0.1:8787';
const health = await (await fetch(`${base}/api/health`)).json();
assert.equal(health.mode,'live','Smoke test requires the live Worker, never fixtures');
assert.equal(health.aiBinding,true);
const contextMode=process.env.CONTEXT_MODE ?? 'retrieved';
assert.ok(['retrieved','none'].includes(contextMode));
const request = {question:'How many trips had pickups in January 2024?',contextMode};
const started=performance.now();
const response=await fetch(`${base}/api/generate`,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(request)});
const body=await response.json();
const report={verifiedAt:new Date().toISOString(),provenance:'one live Workers AI request; no dataset/query execution in this script',request,status:response.status,elapsedMs:Math.round(performance.now()-started),response:body};
await writeFile(contextMode === 'none' ? 'data/live-smoke-none.json' : 'data/live-smoke.json',JSON.stringify(report,null,2)+'\n');
assert.equal(response.status,200,JSON.stringify(body.error ?? body));
assert.equal(body.mode,'live'); assert.equal(body.model,health.model);
assert.equal(body.executableSql,validateSql(body.sql).executionSql);
assert.ok(Array.isArray(body.snippets));
console.log(JSON.stringify(report,null,2));
